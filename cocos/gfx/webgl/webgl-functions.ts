    gl = {} as WebGLRenderingContext;
    // WebGL 1.0
    gl.activeTexture = context.activeTexture;
    gl.attachShader = context.attachShader;
    gl.bindAttribLocation = context.bindAttribLocation;
    gl.bindBuffer = context.bindBuffer;
    gl.bindFramebuffer = context.bindFramebuffer;
    gl.bindRenderbuffer = context.bindRenderbuffer;
    gl.bindTexture = context.bindTexture;
    gl.blendColor = context.blendColor;
    gl.blendEquation = context.blendEquation;
    gl.blendEquationSeparate = context.blendEquationSeparate;
    gl.blendFunc = context.blendFunc;
    gl.blendFuncSeparate = context.blendFuncSeparate;
    gl.checkFramebufferStatus = context.checkFramebufferStatus;
    gl.clear = context.clear;
    gl.clearColor = context.clearColor;
    gl.clearDepth = context.clearDepth;
    gl.clearStencil = context.clearStencil;
    gl.colorMask = context.colorMask;
    gl.compileShader = context.compileShader;
    gl.copyTexImage2D = context.copyTexImage2D;
    gl.copyTexSubImage2D = context.copyTexSubImage2D;
    gl.createBuffer = context.createBuffer;
    gl.createFramebuffer = context.createFramebuffer;
    gl.createProgram = context.createProgram;
    gl.createRenderbuffer = context.createRenderbuffer;
    gl.createShader = context.createShader;
    gl.createTexture = context.createTexture;
    gl.cullFace = context.cullFace;
    gl.deleteBuffer = context.deleteBuffer;
    gl.deleteFramebuffer = context.deleteFramebuffer;
    gl.deleteProgram = context.deleteProgram;
    gl.deleteRenderbuffer = context.deleteRenderbuffer;
    gl.deleteShader = context.deleteShader;
    gl.deleteTexture = context.deleteTexture;
    gl.depthFunc = context.depthFunc;
    gl.depthMask = context.depthMask;
    gl.depthRange = context.depthRange;
    gl.detachShader = context.detachShader;
    gl.disable = context.disable;
    gl.disableVertexAttribArray = context.disableVertexAttribArray;
    gl.drawArrays = context.drawArrays;
    gl.drawElements = context.drawElements;
    gl.enable = context.enable;
    gl.enableVertexAttribArray = context.enableVertexAttribArray;
    gl.finish = context.finish;
    gl.flush = context.flush;
    gl.framebufferRenderbuffer = context.framebufferRenderbuffer;
    gl.framebufferTexture2D = context.framebufferTexture2D;
    gl.frontFace = context.frontFace;
    gl.generateMipmap = context.generateMipmap;
    gl.getActiveAttrib = context.getActiveAttrib;
    gl.getActiveUniform = context.getActiveUniform;
    gl.getAttachedShaders = context.getAttachedShaders;
    gl.getAttribLocation = context.getAttribLocation;
    gl.getBufferParameter = context.getBufferParameter;
    gl.getContextAttributes = context.getContextAttributes;
    gl.getError = context.getError;
    gl.getExtension = context.getExtension;
    gl.getFramebufferAttachmentParameter = context.getFramebufferAttachmentParameter;
    gl.getParameter = context.getParameter;
    gl.getProgramInfoLog = context.getProgramInfoLog;
    gl.getProgramParameter = context.getProgramParameter;
    gl.getRenderbufferParameter = context.getRenderbufferParameter;
    gl.getShaderInfoLog = context.getShaderInfoLog;
    gl.getShaderParameter = context.getShaderParameter;
    gl.getShaderPrecisionFormat = context.getShaderPrecisionFormat;
    gl.getShaderSource = context.getShaderSource;
    gl.getSupportedExtensions = context.getSupportedExtensions;
    gl.getTexParameter = context.getTexParameter;
