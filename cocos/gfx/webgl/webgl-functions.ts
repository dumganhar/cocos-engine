    gl.texImage2D = context.texImage2D;
    gl.texSubImage2D = context.texSubImage2D;
    gl.uniform1fv = context.uniform1fv;
    gl.uniform1iv = context.uniform1iv;
    gl.uniform2fv = context.uniform2fv;
    gl.uniform2iv = context.uniform2iv;
    gl.uniform3fv = context.uniform3fv;
    gl.uniform3iv = context.uniform3iv;
    gl.uniform4fv = context.uniform4fv;
